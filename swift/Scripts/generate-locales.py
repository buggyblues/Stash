#!/usr/bin/env python3
"""Generate the Swift localization tables from the canonical JSON bundles.

The JSON files in ``swift/Resources/Locales`` are the single source of truth
for every user facing string. This script mirrors them into
``Sources/StashCore/Services/Locales.swift`` so the native app ships with the
exact same wording in all three languages.

Usage:
    python3 Scripts/generate-locales.py [--check]
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys

REPO_ROOT = pathlib.Path(__file__).resolve().parents[2]
LOCALE_DIR = REPO_ROOT / "swift" / "Resources" / "Locales"
OUTPUT = REPO_ROOT / "swift" / "Sources" / "StashCore" / "Services" / "Locales.swift"

BUNDLES = [
    ("zhCN", "zh-CN.json"),
    ("english", "en.json"),
    ("zhTW", "zh-TW.json"),
]


def swift_string(value: str) -> str:
    escaped = (
        value.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\r", "\\r")
        .replace("\t", "\\t")
    )
    return f'"{escaped}"'


def render(bundles: list[tuple[str, dict[str, str]]]) -> str:
    lines = [
        "// Generated by Scripts/generate-locales.py — do not edit by hand.",
        "// Source of truth: swift/Resources/Locales/*.json",
        "",
        "import Foundation",
        "",
        "/// The translated strings for every supported language.",
        "public enum Locales {",
    ]

    for name, entries in bundles:
        lines.append(f"    public static let {name}: [String: String] = [")
        for key, value in entries.items():
            lines.append(f"        {swift_string(key)}: {swift_string(value)},")
        lines.append("    ]")
        lines.append("")

    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail when the generated file is stale")
    args = parser.parse_args()

    bundles: list[tuple[str, dict[str, str]]] = []
    for name, filename in BUNDLES:
        path = LOCALE_DIR / filename
        with path.open("r", encoding="utf-8") as handle:
            bundles.append((name, json.load(handle)))

    # Every bundle must expose the same keys.
    canonical = set(bundles[0][1].keys())
    for name, entries in bundles[1:]:
        if set(entries.keys()) != canonical:
            missing = sorted(canonical - set(entries.keys()))
            extra = sorted(set(entries.keys()) - canonical)
            print(f"key mismatch in {name}: missing={missing} extra={extra}", file=sys.stderr)
            return 1

    rendered = render(bundles)

    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != rendered:
            print("Locales.swift is out of date; run Scripts/generate-locales.py", file=sys.stderr)
            return 1
        print("Locales.swift is up to date")
        return 0

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(rendered, encoding="utf-8")
    print(f"wrote {OUTPUT} ({len(canonical)} keys)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
